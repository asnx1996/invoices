-- 012: أكثر من بورد (المنطقة الوسطى، الجنوبية...) معزولة عن بعض
--   • boards: البوردات. الطلبات الحالية كلها تروح لبورد رقم 1 "المنطقة الوسطى"
--   • board_members: الأدمن يحدد كل مستخدم يا بوردات يشوف. الأدمن يشوف الكل
--   • الدور (مندوب/محاسب...) نفسه بكل البوردات؛ البورد يحدد بس وين يشتغل
--   • العزل بالقاعدة: القراءة، الإنشاء، التعديل، الإجراءات، الإشعارات، الملفات، الربح، التقارير
--   • نقل طلب لبورد ثاني: الأدمن فقط (inv_set_board)
--   • كل المستخدمين الحاليين ينضافون لبورد "المنطقة الوسطى" حتى ما يتغير شي عليهم
-- يتشغل بعد 011. آمن للتشغيل أكثر من مرة.
begin;

-- ============================================================
-- 1) الجداول
-- ============================================================
create table if not exists public.boards (
  id bigint generated by default as identity primary key,
  name text not null unique check (btrim(name) <> ''),
  created_at timestamptz not null default now()
);
insert into public.boards (id, name) values (1, 'المنطقة الوسطى') on conflict (id) do nothing;
select setval(pg_get_serial_sequence('public.boards', 'id'), greatest((select max(id) from public.boards), 1));

create table if not exists public.board_members (
  board_id bigint not null references public.boards (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  primary key (board_id, user_id)
);
create index if not exists board_members_user_idx on public.board_members (user_id);

-- المستخدمين الحاليين كلهم بالبورد الأول (مثل ما كانوا)
insert into public.board_members (board_id, user_id)
select 1, id from public.profiles on conflict do nothing;

alter table public.invoices add column if not exists board_id bigint not null default 1 references public.boards (id);
create index if not exists invoices_board_idx on public.invoices (board_id);

-- ============================================================
-- 2) دوال مساعدة
-- ============================================================
-- بوردات المستخدم الحالي (الأدمن: كلها). موقوف = ولا واحد
create or replace function public.my_boards()
returns bigint[] language sql stable security definer set search_path = public as $$
  select case
    when not public.is_active() then '{}'::bigint[]
    when public.has_role('admin') then array(select id from public.boards)
    else array(select board_id from public.board_members where user_id = auth.uid())
  end
$$;

create or replace function public.in_board(p_board bigint)
returns boolean language sql stable security definer set search_path = public as $$
  select p_board = any(public.my_boards())
$$;

-- ============================================================
-- 3) سياسات الجداول الجديدة
-- ============================================================
alter table public.boards enable row level security;
alter table public.board_members enable row level security;

drop policy if exists boards_read on public.boards;
create policy boards_read on public.boards for select to authenticated
  using (id = any((select public.my_boards())::bigint[]));
drop policy if exists boards_admin_ins on public.boards;
create policy boards_admin_ins on public.boards for insert to authenticated with check ((select public.has_role('admin')));
drop policy if exists boards_admin_upd on public.boards;
create policy boards_admin_upd on public.boards for update to authenticated
  using ((select public.has_role('admin'))) with check ((select public.has_role('admin')));

-- كل واحد يشوف أعضاء بورداته (للمنشن وقائمة المندوبين)
drop policy if exists board_members_read on public.board_members;
create policy board_members_read on public.board_members for select to authenticated
  using (board_id = any((select public.my_boards())::bigint[]));
drop policy if exists board_members_admin_ins on public.board_members;
create policy board_members_admin_ins on public.board_members for insert to authenticated with check ((select public.has_role('admin')));
drop policy if exists board_members_admin_del on public.board_members;
create policy board_members_admin_del on public.board_members for delete to authenticated using ((select public.has_role('admin')));

grant select, insert, update on public.boards to authenticated;
grant select, insert, delete on public.board_members to authenticated;
revoke all on public.boards, public.board_members from anon;

-- ============================================================
-- 4) سياسات الطلبات: نفس 004 + لازم الطلب ضمن بوردات المستخدم
-- ============================================================
drop policy if exists invoices_read on public.invoices;
create policy invoices_read on public.invoices for select to authenticated using (
  board_id = any((select public.my_boards())::bigint[]) and (
    (select public.has_role('admin')) or (select public.has_role('mgr')) or (select public.has_role('acc'))
    or ((select public.has_role('wh')) and stage in ('decision', 'done'))
    or ((select public.has_role('rep')) and rep_id = (select auth.uid())))
);

drop policy if exists invoices_insert on public.invoices;
create policy invoices_insert on public.invoices for insert to authenticated with check (
  stage = 'new' and board_id = any((select public.my_boards())::bigint[]) and ((select public.has_role('admin'))
    or ((select public.has_role('rep')) and rep_id = (select auth.uid())))
);

drop policy if exists invoices_update on public.invoices;
create policy invoices_update on public.invoices for update to authenticated
  using (board_id = any((select public.my_boards())::bigint[]) and ((select public.has_role('admin'))
    or ((select public.has_role('rep')) and rep_id = (select auth.uid()) and stage = 'new')
    or ((select public.has_role('acc')) and stage = 'acc')))
  with check (board_id = any((select public.my_boards())::bigint[]) and ((select public.has_role('admin'))
    or ((select public.has_role('rep')) and rep_id = (select auth.uid()) and stage = 'new')
    or ((select public.has_role('acc')) and stage = 'acc')));

-- نفس invoices_read — للدوال اللي تشتغل كـ definer (تعليقات، طلب حذف...)
create or replace function public.can_see_invoice(p_id bigint)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.invoices i where i.id = p_id and public.in_board(i.board_id) and (
      public.has_role('admin') or public.has_role('mgr') or public.has_role('acc')
      or (public.has_role('wh') and i.stage in ('decision', 'done'))
      or (public.has_role('rep') and i.rep_id = auth.uid())))
$$;

-- الإشعارات: محد يوصله إشعار عن طلب ببورد مو إله
create or replace function public.user_can_see_invoice(p_user uuid, p_id bigint)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.invoices i join public.profiles p on p.id = p_user and p.active
     where i.id = p_id
       and ('admin' = any(p.roles)
            or exists (select 1 from public.board_members m where m.board_id = i.board_id and m.user_id = p_user))
       and ('admin' = any(p.roles) or 'mgr' = any(p.roles) or 'acc' = any(p.roles)
            or ('wh' = any(p.roles) and i.stage in ('decision', 'done'))
            or ('rep' = any(p.roles) and i.rep_id = p_user)))
$$;
revoke execute on function public.user_can_see_invoice(uuid, bigint) from public, anon, authenticated;

-- ============================================================
-- 5) حارس البورد: يشمل الإجراءات (دوال definer) مو بس التعديل المباشر
--    أي تعديل على طلب ببورد مو إلك ينرفض، ونقل البورد للأدمن فقط
-- ============================================================
create or replace function public.invoices_board_guard()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then return new; end if;   -- SQL Editor / cron
  if not public.in_board(old.board_id) then raise exception 'الطلب مو ضمن بورداتك'; end if;
  if new.board_id is distinct from old.board_id then
    if not public.has_role('admin') then raise exception 'نقل الطلب لبورد ثاني للأدمن فقط'; end if;
    if not exists (select 1 from public.boards where id = new.board_id) then raise exception 'البورد غير موجود'; end if;
  end if;
  return new;
end $$;
revoke execute on function public.invoices_board_guard() from public, anon, authenticated;
drop trigger if exists invoices_board_guard_trg on public.invoices;
create trigger invoices_board_guard_trg before update on public.invoices
  for each row execute function public.invoices_board_guard();

-- ============================================================
-- 6) نقل طلب لبورد ثاني (الأدمن)
-- ============================================================
create or replace function public.inv_set_board(p_id bigint, p_board bigint)
returns public.invoices language plpgsql security definer set search_path = public as $$
declare v public.invoices; b text;
begin
  if not public.has_role('admin') then raise exception 'نقل الطلب لبورد ثاني للأدمن فقط'; end if;
  select name into b from public.boards where id = p_board;
  if b is null then raise exception 'البورد غير موجود'; end if;
  select * into v from public.invoices where id = p_id for update;
  if v is null then raise exception 'الطلب غير موجود'; end if;
  if v.board_id = p_board then return v; end if;
  update public.invoices set board_id = p_board where id = p_id returning * into v;
  perform public.add_log(p_id, 'نقل الطلب لبورد ' || b);
  return v;
end $$;

-- ============================================================
-- 7) الربح والتقارير حسب البورد
-- ============================================================
create or replace function public.inv_profits(p_ids bigint[] default null)
returns table (invoice_id bigint, total numeric, gross_pct numeric, net_pct numeric)
language sql stable security definer set search_path = public as $$
  select p.invoice_id, p.total, p.gross_pct, p.net_pct
    from public.inv_profit_rows() p
    join public.invoices i on i.id = p.invoice_id
   where (p_ids is null or p.invoice_id = any(p_ids))
     and public.in_board(i.board_id)
     and (public.has_role('admin')
          or (public.has_role('mgr') and p.stage in ('decision', 'done', 'cancel')))
$$;

drop function if exists public.report_summary(date, date);
create or replace function public.report_summary(p_from date, p_to date, p_board bigint default 1)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare res jsonb;
begin
  if not (public.has_role('admin') or public.has_role('mgr')) then raise exception 'التقارير للأدمن والمدير'; end if;
  if not public.in_board(p_board) then raise exception 'ما عندك صلاحية على هذا البورد'; end if;

  with inv as (
    select i.*, p.net_pct
      from public.invoices i
      left join public.inv_profit_rows() p on p.invoice_id = i.id
     where i.board_id = p_board and i.created_at >= p_from and i.created_at < (p_to + 1)
  ),
  seg as (
    select s.stage, s.sub,
           extract(epoch from (coalesce(lead(s.at) over w, case when i.stage in ('new','acc','decision') then now() end) - s.at)) / 86400 as days
      from public.invoice_stage_log s
      join inv i on i.id = s.invoice_id
    window w as (partition by s.invoice_id order by s.at, s.id)
  )
  select jsonb_build_object(
    'totals', (select jsonb_build_object(
        'count', count(*),
        'active', count(*) filter (where stage in ('new','acc','decision')),
        'done', count(*) filter (where stage = 'done'),
        'cancel', count(*) filter (where stage = 'cancel'),
        'done_value', coalesce(sum(value) filter (where stage = 'done'), 0),
        'late', count(*) filter (where stage in ('new','acc','decision') and stage_at < now() - interval '3 days'),
        'avg_cycle_days', round(avg(extract(epoch from (closed_at - created_at)) / 86400) filter (where stage = 'done')::numeric, 1),
        'avg_net_pct', round(avg(net_pct) filter (where stage = 'done'), 2)) from inv),
    'by_rep', coalesce((select jsonb_agg(r order by r.done_value desc) from (
        select coalesce(pr.full_name, '—') as rep, count(*) as total,
               count(*) filter (where i.stage in ('new','acc','decision')) as active,
               count(*) filter (where i.stage = 'done') as done,
               count(*) filter (where i.stage = 'cancel') as cancel,
               coalesce(sum(i.value) filter (where i.stage = 'done'), 0) as done_value,
               round(avg(extract(epoch from (i.closed_at - i.created_at)) / 86400) filter (where i.stage = 'done')::numeric, 1) as avg_cycle_days,
               round(avg(i.net_pct) filter (where i.stage = 'done'), 2) as avg_net_pct
          from inv i left join public.profiles pr on pr.id = i.rep_id
         group by pr.full_name) r), '[]'::jsonb),
    'by_month', coalesce((select jsonb_agg(m order by m.month) from (
        select to_char(date_trunc('month', closed_at), 'YYYY-MM') as month,
               count(*) as done, coalesce(sum(value), 0) as value, round(avg(net_pct), 2) as avg_net_pct
          from inv where stage = 'done' group by 1) m), '[]'::jsonb),
    'stages', coalesce((select jsonb_agg(x order by x.ord) from (
        select case when stage = 'decision' then 'decision:' || coalesce(sub, '') else stage end as key,
               case stage when 'new' then 1 when 'acc' then 2 else
                 case sub when 'mgr' then 3 when 'cust' then 4 when 'wh' then 5 else 6 end end as ord,
               count(*) as n, round(avg(days)::numeric, 1) as avg_days
          from seg where stage in ('new','acc','decision') and days is not null group by 1, 2) x), '[]'::jsonb),
    'cancel_reasons', coalesce((select jsonb_agg(c) from (
        select btrim(cancel_reason) as reason, count(*) as n from inv
         where stage = 'cancel' and btrim(coalesce(cancel_reason,'')) <> ''
         group by 1 order by 2 desc limit 10) c), '[]'::jsonb)
  ) into res;
  return res;
end $$;

-- ============================================================
-- 8) إنشاء مستخدم مع بورداته (بدون بوردات = البورد الأول)
-- ============================================================
drop function if exists public.admin_create_user(text, text, text, public.app_role[]);
create or replace function public.admin_create_user(
  p_username text, p_password text, p_full_name text, p_roles public.app_role[], p_boards bigint[] default null)
returns uuid language plpgsql security definer set search_path = public, extensions as $$
declare
  uid uuid := gen_random_uuid();
  em  text := public.admin_login_email(p_username);
begin
  if not public.has_role('admin') then raise exception 'للأدمن فقط'; end if;
  if length(coalesce(p_password, '')) < 8 then raise exception 'الرمز لازم 8 أحرف على الأقل'; end if;
  if btrim(coalesce(p_full_name, '')) = '' then raise exception 'الاسم الكامل مطلوب'; end if;
  if coalesce(cardinality(p_roles), 0) = 0 then raise exception 'اختار دور واحد على الأقل'; end if;
  if exists (select 1 from auth.users where lower(email) = em) then
    raise exception 'اسم المستخدم موجود، اختار غيره'; end if;

  insert into auth.users (
    instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
    raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
    confirmation_token, recovery_token, email_change_token_new, email_change,
    email_change_token_current, reauthentication_token, phone_change, phone_change_token)
  values (
    '00000000-0000-0000-0000-000000000000', uid, 'authenticated', 'authenticated', em,
    crypt(p_password, gen_salt('bf')), now(),
    '{"provider":"email","providers":["email"]}'::jsonb,
    jsonb_build_object('full_name', btrim(p_full_name)), now(), now(),
    '', '', '', '', '', '', '', '');

  insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
  values (gen_random_uuid(), uid, uid::text,
          jsonb_build_object('sub', uid::text, 'email', em, 'email_verified', true),
          'email', now(), now(), now());

  insert into public.profiles (id, full_name, roles, active)
  values (uid, btrim(p_full_name), p_roles, true)
  on conflict (id) do update set full_name = excluded.full_name, roles = excluded.roles, active = true;

  insert into public.board_members (board_id, user_id)
  select b.id, uid from public.boards b
   where b.id = any(case when coalesce(cardinality(p_boards), 0) = 0 then array[1::bigint] else p_boards end)
  on conflict do nothing;
  return uid;
end $$;

